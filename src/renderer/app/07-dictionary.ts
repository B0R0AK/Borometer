import type { I18nEntry, I18nVars, Lang } from "../types";

/* Der leise Befund zur Unverwundbarkeit (insight.invulnCasts, Issue #37):
   "2 Einsaetze von A und 1 von B gingen ins unverwundbare Ziel (0:57-1:04)". */
type Teil = { n: number; skill: string };
const liste = (xs: string[], und: string) =>
  xs.length < 2 ? xs.join("") : xs.slice(0, -1).join(", ") + " " + und + " " + xs[xs.length - 1];
const spanne = (v: I18nVars) => v.from === v.to ? v.from : v.from + "\u2013" + v.to;
const invulnEn = (v: I18nVars) => liste((v.teile as Teil[] || []).map((p, i) =>
    p.n + (i ? "" : p.n === 1 ? " cast" : " casts") + " of " + p.skill), "and") +
  " went into the invulnerable target (" + spanne(v) + ").";
const invulnDe = (v: I18nVars) => liste((v.teile as Teil[] || []).map((p, i) =>
    p.n + (i ? "" : p.n === 1 ? " Einsatz" : " Einsätze") + " von " + p.skill), "und") +
  (v.n === 1 ? " ging" : " gingen") + " ins unverwundbare Ziel (" + spanne(v) + ").";

