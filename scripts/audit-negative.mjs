      // "rename": die Datei (nur in der Kopie) bekommt den Namen der Einfuegung, relativ zu ihrem Ordner -
      // so prueft ein Fall, dass eine Regel die Datei unter ihrem Namen verlangt
      if (how === "rename") {
        if (!existsSync(p)) return [`  SKIP  ${name} (file missing)`, true];
        renameSync(p, join(dirname(p), insert));
      } else writeFileSync(p, src.replace(at, (m) => (how === "replace" ? insert : m + "\n" + insert)));
