/* Nur lokal: AUDIT_NEGATIVE_NUR="text" fuehrt nur Faelle aus, deren Name "text" enthaelt
   (ein Gesamtlauf dauert Stunden). Die CI setzt es nie; ohne die Variable laeuft jeder Fall,
   und ein Teillauf sagt es laut. */
const nur = process.env.AUDIT_NEGATIVE_NUR || "";
const lauf = nur ? cases.filter((c) => c[0].includes(nur)) : cases;
if (nur) console.log(`TEILLAUF: nur Faelle mit "${nur}" (${lauf.length} von ${cases.length})`);
if (nur && !lauf.length) { console.log("TEILLAUF FAILED - kein Fall passt"); process.exit(1); }
/* Jeder Fall arbeitet in seinem eigenen Ordner und startet sein eigenes Audit, also laufen
   so viele zugleich, wie der Rechner Kerne hat. Die Zeilen kommen trotzdem in der
   Reihenfolge der Liste. */
function auditLauf(env) {
  return new Promise((fertig) => {
    const c = spawn(process.execPath, [join(root, "scripts", "safety-audit.mjs")], { env });
    let stdout = "";
    c.stdout.setEncoding("utf8").on("data", (d) => { stdout += d; });
    c.stderr.resume();
    c.on("error", () => fertig({ status: null, stdout }));
    c.on("close", (status) => fertig({ status, stdout }));
  });
}
